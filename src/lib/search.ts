const ZWNJ = "\u200C"; // نیم‌فاصله

/**
 * چون تو فارسی نیم‌فاصله خیلی وقت‌ها به‌جای فاصله‌ی معمولی (یا هیچی) تایپ
 * می‌شه — و برعکس — یه جستجوی ساده‌ی contains ممکنه «فرانت‌اند» (با نیم‌فاصله)
 * رو وقتی کاربر «فرانت اند» (با فاصله‌ی معمولی) سرچ می‌کنه پیدا نکنه.
 *
 * این تابع چند تا نسخه‌ی معادل از عبارت جستجو می‌سازه (با نیم‌فاصله، بدون
 * نیم‌فاصله، با فاصله‌ی معمولی به‌جای نیم‌فاصله و...) تا هرکدوم که با چیزی که
 * تو دیتابیس ذخیره شده match بشه، نتیجه برگرده. خروجی همیشه شامل خودِ عبارت
 * اصلی هم هست.
 */
export function buildSearchTerms(rawQuery: string): string[] {
  const q = rawQuery.trim();
  if (!q) return [];

  const variants = new Set<string>([
    q,
    q.replaceAll(ZWNJ, ""), // نیم‌فاصله حذف بشه: «فرانت‌اند» → «فرانتاند»
    q.replaceAll(ZWNJ, " ").replace(/\s+/g, " ").trim(), // نیم‌فاصله بشه فاصله: «فرانت‌اند» → «فرانت اند»
    q.replace(/\s+/g, ZWNJ), // فاصله بشه نیم‌فاصله: «فرانت اند» → «فرانت‌اند»
    q.replace(/[\s\u200C]+/g, ""), // همه‌ی فاصله‌ها/نیم‌فاصله‌ها حذف بشن: «فرانت اند» → «فرانتاند»
  ]);

  return [...variants].filter(Boolean);
}